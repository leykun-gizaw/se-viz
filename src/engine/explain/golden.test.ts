/**
 * Golden tests for the derived explanations (Phase 32). For every Phase 29 sample, the Phase 32 extra
 * programs, and two C modules without authored text, the explanation panel's text for **every step
 * and both beats** is written to a Markdown file in `golden/` — what a reviewer reads to check that
 * every sentence is true for its step. `vitest -u` rewrites them; `CI=1` fails on any drift.
 *
 * The text is `explainBeat`'s (what the panel shows), so it also covers the fallbacks: a step with
 * no derived "What this step did" shows its narration, marked `(narration)`.
 */
