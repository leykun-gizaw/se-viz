/**
 * Golden tests for the derived explanations (Phase 32). For every Phase 29 sample, the Phase 32 extra
 * programs, and two C modules without authored text, the explanation panel's text for **every step
 * and both beats** is written to a Markdown file in `golden/` — what a reviewer reads to check that
 * every sentence is true for its step. `vitest -u` rewrites them; `CI=1` fails on any drift.
 *
 * The text is `explainBeat`'s (what the panel shows), so it also covers the fallbacks: a step with
 * no derived "What this step did" shows its narration, marked `(narration)`.
 */
import { describe, expect, it } from 'vitest';
import { controlFlowTrace } from '../../content/se200/variables-control-flow/controlFlow.ts';
import { sumToTrace } from '../../content/se200/recursion/sumTo.ts';
import type { RunResult } from '../../python/protocol.ts';
import { EXTRA_PROGRAMS } from '../../python/testPrograms.ts';
import { recordingToTrace } from '../../python/toTrace.ts';
import { explainBeat } from '../trace/explain.ts';
import { lineTexts } from '../trace/labels.ts';
import type { Trace } from '../trace/types.ts';
import type { ChangeRow } from './types.ts';

const TRACES = import.meta.glob<Trace>('../../content/fixtures/python/*.json', {
  eager: true,
  import: 'default',
});
const RECORDINGS = import.meta.glob<string>('../../python/fixtures/extra-*.json', {
  query: '?raw',
  import: 'default',
  eager: true,
});

const sample = (name: string) => {
  const t = TRACES[`../../content/fixtures/python/${name}.json`];
  if (!t) throw new Error(`missing trace ${name}`);
  return t;
};

/** A Phase 32 extra program, recorded by `recorder.test.ts` and mapped like any live run. */
function extra(name: string): Trace {
  const text = RECORDINGS[`../../python/fixtures/${name}.json`];
  const program = EXTRA_PROGRAMS.find((p) => p.name === name);
  if (text === undefined || !program) throw new Error(`missing recording ${name}`);
  return recordingToTrace(JSON.parse(text) as RunResult, program.request.source, {
    id: name,
    title: name,
    file: `${name}.py`,
  });
}

function rowText(row: ChangeRow): string {
  const value =
    row.to !== undefined ? (row.from !== undefined ? `: ${row.from} → ${row.to}` : ` = ${row.to}`) : '';
  if (row.kind === 'output') return `[output] ${row.subject.split('\n').join(' ⏎ ')}`;
  return `[${row.kind}] ${row.subject}${value}`;
}

/** The panel's text for every step of a trace, both beats, as Markdown. */
export function renderGolden(trace: Trace): string {
  const out: string[] = [];
  const fence = trace.language === 'python' ? 'python' : 'c';
  out.push(`# ${trace.file ?? trace.id}: derived explanations`, '');
  out.push(
    'Generated by `src/engine/explain/golden.test.ts` from what the explanation panel shows ' +
      '(`explainBeat`, two-beat mode). Review every sentence against its step.',
    '',
  );
  out.push('```' + fence);
  trace.source
    .replace(/\n$/, '')
    .split('\n')
    .forEach((l, i) => out.push(`${String(i + 1).padStart(2)}  ${l}`));
  out.push('```', '');
  trace.steps.forEach((step, i) => {
    const code = lineTexts(trace.source, step.highlightedLines).join(' / ');
    out.push(`## Step ${i + 1} · line ${step.highlightedLines.join(', ')} · \`${code}\``, '');
    const arrive = explainBeat(trace, i, 'arrive', 'two-beat');
    const apply = explainBeat(trace, i, 'apply', 'two-beat');
    out.push(`**Arrive:** ${arrive.did ? arrive.did.items.join(' ') : '(nothing derived)'}`, '');
    if (arrive.concept !== apply.concept && arrive.concept) {
      out.push(`**Arrive concept:** ${arrive.concept}`, '');
    }
    out.push('**What this step did**' + (apply.did && !apply.did.markdown ? ' (narration)' : ''), '');
    (apply.did?.items ?? []).forEach((d, n) => out.push(`${n + 1}. ${d}`));
    out.push('');
    out.push('**What changed**', '');
    if (apply.changesNote) out.push(`- (${apply.changesNote})`);
    else if (apply.changes && apply.changes.length === 0) out.push('- Nothing changed');
    for (const row of apply.changes ?? []) out.push(`- ${rowText(row)}`);
    out.push('');
    for (const [title, items] of [
      ['Branch taken', apply.branch],
      ['Loop iteration', apply.loop],
      ['Calls and returns', apply.calls],
      ['Exceptions', apply.exceptions],
    ] as const) {
      if (items.length === 0) continue;
      out.push(`**${title}**`, '', ...items.map((t) => `- ${t}`), '');
    }
    if (apply.concept) out.push(`**Concept:** ${apply.concept}`, '');
    out.push(`**Narration:** ${step.narration}`, '');
    if (step.condition) {
      out.push(`**Condition chip:** \`${step.condition.expr}\` → ${String(step.condition.result)}`, '');
    }
  });
  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

const PYTHON_SAMPLES = [
  'aliasing',
  'mutation-through-argument',
  'nested-containers',
  'recursion',
  'class-instances',
  'harvest',
  'runtime-error',
  'infinite-loop',
];
const PYTHON_EXTRAS = ['extra-augassign', 'extra-statements', 'extra-exceptions', 'extra-objects'];

describe('golden derived explanations', () => {
  it.each(PYTHON_SAMPLES)('Phase 29 sample %s', async (name) => {
    await expect(renderGolden(sample(name))).toMatchFileSnapshot(`golden/${name}.md`);
  });

  it.each(PYTHON_EXTRAS)('Phase 32 program %s', async (name) => {
    await expect(renderGolden(extra(name))).toMatchFileSnapshot(`golden/${name}.md`);
  });

  it.each([
    ['c-control-flow', controlFlowTrace],
    ['c-sum-to', sumToTrace],
  ] as const)('C module without authored text: %s', async (name, trace) => {
    await expect(renderGolden(trace)).toMatchFileSnapshot(`golden/${name}.md`);
  });
});
