function rowText(row: ChangeRow): string {
  const value =
    row.to !== undefined
      ? row.from !== undefined
        ? `: ${row.from} → ${row.to}`
        : ` = ${row.to}`
      : '';
  if (row.kind === 'output') return `[output] ${row.subject.split('\n').join(' ⏎ ')}`;
  return `[${row.kind}] ${row.subject}${value}`;
}

/**
 * Phase 37: the state of a generated concept-view step, in one line, so a reviewer can check each
 * sentence against what the view shows. Empty for every other view.
 */
function stateLine(step: Step): string | null {
  const r = (x: number) => String(Math.round(x * 1000) / 1000);
  if (step.bars) {
    const b = step.bars;
    const parts = [`values [${b.values.join(', ')}]`];
    if (b.compared?.length) parts.push(`compared ${b.compared.join(',')}`);
    if (b.swapped?.length) parts.push(`swapped/written ${b.swapped.join(',')}`);
    if (b.sorted?.length) parts.push(`sorted ${b.sorted.join(',')}`);
    if (b.range) parts.push(`range ${b.range.from}–${b.range.to}`);
    if (b.pointers?.length)
      parts.push(`pointers ${b.pointers.map((p) => `${p.label}=${p.index}`).join(' ')}`);
    if (b.found !== undefined) parts.push(`found ${b.found}`);
    if (b.segments) {
      const active = b.segments.filter((s) => s.state === 'active' || s.state === 'split');
      parts.push(
        `segments ${active.map((s) => `${s.from}–${s.to}:${s.state}`).join(' ') || '(none open)'}`,
      );
    }
    parts.push(
      `counters ${Object.entries(b.counters)
        .map(([k, v]) => `${k}=${v}`)
        .join(' ')}`,
    );
    return parts.join(' · ');
  }
  if (step.growth) {
    const g = step.growth;
    return `n = ${g.n} · ${g.curves.map((c) => `${c.label}=${r(c.counts[g.n - 1])}`).join(' ')} · compare ${g.compare?.join(' vs ')}`;
  }
  if (step.distribution) {
    const d = step.distribution;
    const parts = [`draws ${d.draws}`];
    if (d.latest?.length) parts.push(`latest ${d.latest.map(r).join(', ')}`);
    if (d.stats)
      parts.push(`mean ${r(d.stats.mean)} sd ${r(d.stats.sd)} skew ${r(d.stats.skewness)}`);
    if (d.test) parts.push(`extreme ${d.test.extreme} · p ${r(d.test.pValue)} (${d.test.tail})`);
    return parts.join(' · ');
  }
  return null;
}

/** The panel's text for every step of a trace, both beats, as Markdown. */
function renderGolden(trace: Trace): string {
  const out: string[] = [];
  const fence = trace.language === 'python' ? 'python' : 'c';
  out.push(`# ${trace.file ?? trace.id}: derived explanations`, '');
  out.push(
    'Generated by `src/engine/explain/golden.test.ts` from what the explanation panel shows ' +
      '(`explainBeat`, two-beat mode). Review every sentence against its step.',
    '',
  );
  // A generated concept view (Phase 37) has no source: its state line stands in for it.
  if (trace.source !== '') {
    out.push('```' + fence);
    trace.source
      .replace(/\n$/, '')
      .split('\n')
      .forEach((l, i) => out.push(`${String(i + 1).padStart(2)}  ${l}`));
    out.push('```', '');
  }
  trace.steps.forEach((step, i) => {
    const code = lineTexts(trace.source, step.highlightedLines).join(' / ');
    out.push(
      trace.source === ''
        ? `## Step ${i + 1}`
        : `## Step ${i + 1} · line ${step.highlightedLines.join(', ')} · \`${code}\``,
      '',
    );
    const state = stateLine(step);
    if (state) out.push(`**State:** ${state}`, '');
    const arrive = explainBeat(trace, i, 'arrive', 'two-beat');
    const apply = explainBeat(trace, i, 'apply', 'two-beat');
    out.push(`**Arrive:** ${arrive.did ? arrive.did.items.join(' ') : '(nothing derived)'}`, '');
    if (arrive.concept !== apply.concept && arrive.concept) {
      out.push(`**Arrive concept:** ${arrive.concept}`, '');
    }
    out.push(
      '**What this step did**' + (apply.did && !apply.did.markdown ? ' (narration)' : ''),
      '',
    );
    (apply.did?.items ?? []).forEach((d, n) => out.push(`${n + 1}. ${d}`));
    out.push('');
    out.push('**What changed**', '');
    if (apply.changesNote) out.push(`- (${apply.changesNote})`);
    else if (apply.changes && apply.changes.length === 0) out.push('- Nothing changed');
    for (const row of apply.changes ?? []) out.push(`- ${rowText(row)}`);
    out.push('');
    for (const [title, items] of [
      ['Branch taken', apply.branch],
      ['Loop iteration', apply.loop],
      ['Calls and returns', apply.calls],
      ['Exceptions', apply.exceptions],
    ] as const) {
      if (items.length === 0) continue;
      out.push(`**${title}**`, '', ...items.map((t) => `- ${t}`), '');
    }
    if (apply.concept) out.push(`**Concept:** ${apply.concept}`, '');
    out.push(`**Narration:** ${step.narration}`, '');
    if (step.condition) {
      out.push(
        `**Condition chip:** \`${step.condition.expr}\` → ${String(step.condition.result)}`,
        '',
      );
    }
  });
  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

const PYTHON_SAMPLES = [
  'aliasing',
  'mutation-through-argument',
  'nested-containers',
  'recursion',
  'class-instances',
  'harvest',
  'runtime-error',
  'infinite-loop',
];
const PYTHON_EXTRAS = ['extra-augassign', 'extra-statements', 'extra-exceptions', 'extra-objects'];
/** Phase 34: the recorded NumPy samples (`src/content/fixtures/python/numpy/`). */
const NUMPY_SAMPLES = NUMPY.map((s) => s.name);
/** Phase 35: the recorded pandas samples (`src/content/fixtures/python/pandas/`). */
const PANDAS_SAMPLES = PANDAS.map((s) => s.name);
/** Phase 36: the recorded matplotlib samples (`src/content/fixtures/python/matplotlib/`). */
const MATPLOTLIB_SAMPLES = MATPLOTLIB.map((s) => s.name);

describe('golden derived explanations', () => {
  it.each(PYTHON_SAMPLES)('Phase 29 sample %s', async (name) => {
    await expect(renderGolden(sampleTrace(name))).toMatchFileSnapshot(`golden/${name}.md`);
  });

  it.each(PYTHON_EXTRAS)('Phase 32 program %s', async (name) => {
    await expect(renderGolden(extraTrace(name))).toMatchFileSnapshot(`golden/${name}.md`);
  });

  it.each(NUMPY_SAMPLES)('Phase 34 NumPy sample %s', async (name) => {
    await expect(renderGolden(sampleTrace(`numpy/${name}`))).toMatchFileSnapshot(
      `golden/numpy-${name}.md`,
    );
  });

  it.each(PANDAS_SAMPLES)('Phase 35 pandas sample %s', async (name) => {
    await expect(renderGolden(sampleTrace(`pandas/${name}`))).toMatchFileSnapshot(
      `golden/pandas-${name}.md`,
    );
  });

  it.each(MATPLOTLIB_SAMPLES)('Phase 36 matplotlib sample %s', async (name) => {
    await expect(renderGolden(sampleTrace(`matplotlib/${name}`))).toMatchFileSnapshot(
      `golden/matplotlib-${name}.md`,
    );
  });

  // Phase 37: every generated concept-view module (the generator writes the text; review it here).
  it.each(
    allCatalogModules()
      .map((m) => m.trace)
      .filter((t) => t.id.startsWith('concept-'))
      .map((t) => [t.id, t] as const),
  )('Phase 37 generated concept view %s', async (id, trace) => {
    await expect(renderGolden(trace)).toMatchFileSnapshot(`golden/${id}.md`);
  });

  it.each([
    ['c-control-flow', controlFlowTrace],
    ['c-sum-to', sumToTrace],
  ] as const)('C module without authored text: %s', async (name, trace) => {
    await expect(renderGolden(trace)).toMatchFileSnapshot(`golden/${name}.md`);
  });
});
